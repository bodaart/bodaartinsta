    cap = '\n\n'.join(parts)
    queue.append({'id': sid, 'date': '2026-' + date, 'time': TIME[cat], 'cat': cat, 'ref': f'2026-{date} {LAB[cat]} No.{no:02d} {head}', 'caption': cap})
