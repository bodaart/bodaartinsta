specs, queue = [], []
for date, cat, no, idx, order, title, head, intro, spec_lines, mean, iscd, cta, tags in P:
    p = pf[idx]
    us = ([p['img']] if p.get('img') else []) + (p.get('imgs') or [])
    photos = []
    for k in order:
        f = nm(us[k]); ph = {'f': f}
