det = cv2.QRCodeDetector()

def codes(f):
    im = cv2.imread(SRC + f)
    H, W = im.shape[:2]
    out, allpts = [], []
    for D in (det, cv2.QRCodeDetectorAruco()):
        try:
            ok, pts = D.detectMulti(im)
        except Exception:
            ok, pts = False, None
        if ok and pts is not None:
            allpts += list(pts)
    for q in allpts:
        x0, y0, x1, y1 = q[:, 0].min(), q[:, 1].min(), q[:, 0].max(), q[:, 1].max()
        w, h = x1 - x0, y1 - y0
        out.append([int(max(0, x0 - .35 * w)), int(max(0, y0 - .35 * h)), int(min(W, x1 + .35 * w)), int(min(H, y1 + .75 * h))])
    return out

