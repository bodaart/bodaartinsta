def pick5(tags):
    t = tags.split()
    core = [x for x in ['#음반제작', '#앨범제작', '#CD제작', '#USB음반'] if x in t][:2]
    spec = [x for x in t if x not in core and x not in ('#보다아트', '#그때그시절') and x not in ['#음반제작', '#앨범제작', '#CD제작', '#USB음반']]
    out = core + spec[-2:] + ['#보다아트']
    for x in t:
        if len(out) >= 5: break
        if x not in out: out.append(x)
    return ' '.join(out[:5])
